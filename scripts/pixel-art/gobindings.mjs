// Emits backend/internal/art/sprites_gen.go: the Go-side registry of every sprite the art pipeline produces.
//
// Each theme and creature becomes an exported package-level variable of an opaque id type
// (art.ThemeID / art.SpriteID). Their only field is unexported, so code outside package art can neither
// forge an id nor pass a misspelled one: a monster that references art that does not exist fails to
// compile. The output is gofmt-clean by construction (one declaration per line, no aligned columns).
const pascal = (s) => s.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const q = (s) => JSON.stringify(s);

export const GO_BINDINGS_PATH = "backend/internal/art/sprites_gen.go";

export function goBindings(themes) {
  const names = new Map(), out = [];
  const claim = (name, what) => { if (names.has(name)) throw new Error(`Go identifier ${name} is claimed by both ${names.get(name)} and ${what}`); names.set(name, what); return name; };
  out.push("// Code generated by scripts/pixel-art/build.mjs; DO NOT EDIT.", "// Regenerate with `npm run art:build`.", "", "package art", "");
  const themeVars = themes.map((t) => [claim("Theme" + pascal(t.id), "theme " + t.id), t]);
  for (const [v, t] of themeVars) out.push(`// ${v} is the ${t.name} art theme.`, `var ${v} = ThemeID{${q(t.id)}}`, "");
  const sprites = [];
  for (const t of themes) {
    const tv = themeVars.find(([, x]) => x === t)[0];
    for (const c of t.creatures) {
      const v = claim(pascal(t.id) + pascal(c.id), `creature ${t.id}/${c.id}`), boss = c.tier === "boss";
      out.push(`// ${v} is the ${c.name} sprite sheet.`, `var ${v} = SpriteID{${q(t.id + "/" + c.id)}}`, "");
      sprites.push(`\t{ID: ${v}, Theme: ${tv}, CreatureID: ${q(c.id)}, Name: ${q(c.name)}, Boss: ${boss}, Sheet: ${q(t.id + "/" + c.id + ".png")}, FrameSize: ${boss ? 128 : 64}},`);
    }
  }
  out.push("var themes = []Theme{");
  for (const [v, t] of themeVars) out.push(`\t{ID: ${v}, Name: ${q(t.name)}, Tagline: ${q(t.tagline || "")}},`);
  out.push("}", "", "var sprites = []Sprite{", ...sprites, "}", "");
  return out.join("\n");
}
