// Emits backend/internal/art/rooms_gen.go: the Go-side registry of the room backdrops the art pipeline produces.
// Room kinds are opaque values (like art.SpriteID) and every (theme, kind) pair has exactly one Backdrop entry, so game
// code that needs a backdrop for a room asks the registry and a template that uses a kind without art fails a test.
import { KINDS, VIEWS } from "./styles.mjs";

export const ROOMS_GO_PATH = "backend/internal/art/rooms_gen.go";
const pascal = (s) => s.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const q = (s) => JSON.stringify(s);

export function roomBindings(themes) {
  const out = ["// Code generated by scripts/pixel-art/rooms/build.mjs; DO NOT EDIT.", "// Regenerate with `npm run art:rooms`.", "", "package art", ""];
  for (const k of KINDS) out.push(`// RoomKind${pascal(k)} is the ${k} room kind.`, `var RoomKind${pascal(k)} = RoomKind{${q(k)}}`, "");
  out.push("var roomKinds = []RoomKind{", ...KINDS.map((k) => `\tRoomKind${pascal(k)},`), "}", "", "var backdrops = []Backdrop{");
  for (const t of themes) for (const k of KINDS) out.push(`\t{Theme: Theme${pascal(t.id)}, Kind: RoomKind${pascal(k)}, ${VIEWS.map((v) => `${pascal(v)}: ${q(t.id + "/" + k + "-" + v + ".png")}`).join(", ")}},`);
  out.push("}", "");
  return out.join("\n");
}
